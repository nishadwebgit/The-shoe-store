using ShoeStore.Domain.Common;
using ShoeStore.Domain.Enums;

namespace ShoeStore.Domain.Entities;

/// <summary>A company the store buys stock from.</summary>
public class Supplier : AuditableEntity
{
    public int Id { get; set; }
    public string Name { get; set; } = string.Empty;
    public string? ContactName { get; set; }
    public string? Phone { get; set; }
    public string? Email { get; set; }
    public string? Notes { get; set; }
    public bool IsActive { get; set; } = true;
}

/// <summary>
/// One delivery of stock for one product (a goods received note). Quantities are added to the
/// variants' stock; the receipt and its lines are never edited afterwards.
/// </summary>
public class StockReceipt
{
    public int Id { get; set; }

    /// <summary>Human-friendly number, e.g. GRN-2611-0007.</summary>
    public string ReceiptNumber { get; set; } = string.Empty;

    /// <summary>Generated by the browser for each submission so a double-click can't record a delivery twice.</summary>
    public Guid ClientRequestId { get; set; }

    public int? SupplierId { get; set; }
    public Supplier? Supplier { get; set; }

    /// <summary>Supplier name at the time of receipt (kept even if the supplier is renamed).</summary>
    public string? SupplierName { get; set; }

    /// <summary>Supplier invoice or delivery note number.</summary>
    public string? SupplierReference { get; set; }

    /// <summary>Date the goods arrived (date only, stored at midnight UTC).</summary>
    public DateTime ReceivedDate { get; set; }

    /// <summary>The product received. Null if the product was later deleted (the snapshot below remains).</summary>
    public int? ProductId { get; set; }
    public string ProductCode { get; set; } = string.Empty;
    public string ProductName { get; set; } = string.Empty;

    /// <summary>Cost price per pair, if recorded.</summary>
    public decimal? UnitCost { get; set; }

    /// <summary>Selling price set on the product with this receipt.</summary>
    public decimal SellingPrice { get; set; }

    public string? Notes { get; set; }
    public int TotalQuantity { get; set; }

    public Guid? ReceivedById { get; set; }
    public string ReceivedByName { get; set; } = string.Empty;
    public DateTime CreatedUtc { get; set; }

    public ICollection<StockReceiptItem> Items { get; set; } = new List<StockReceiptItem>();
}

public class StockReceiptItem
{
    public int Id { get; set; }
    public int StockReceiptId { get; set; }
    public StockReceipt StockReceipt { get; set; } = null!;

    /// <summary>Null if the variant was later removed; the snapshot fields remain.</summary>
    public int? ProductVariantId { get; set; }
    public string Sku { get; set; } = string.Empty;
    public string ColourName { get; set; } = string.Empty;
    public string Size { get; set; } = string.Empty;

    public int Quantity { get; set; }
    public int PreviousQuantity { get; set; }
    public int NewQuantity { get; set; }
}

/// <summary>
/// Audit record of one stock movement on one variant. Every change to
/// <see cref="ProductVariant.StockQuantity"/> creates exactly one of these.
/// </summary>
public class InventoryTransaction
{
    public long Id { get; set; }

    /// <summary>Null if the variant was later removed; the snapshot fields remain.</summary>
    public int? ProductVariantId { get; set; }
    public string Sku { get; set; } = string.Empty;
    public string ProductCode { get; set; } = string.Empty;
    public string ProductName { get; set; } = string.Empty;
    public string ColourName { get; set; } = string.Empty;
    public string Size { get; set; } = string.Empty;

    public InventoryTransactionType Type { get; set; }

    /// <summary>Signed change: positive adds stock, negative removes it.</summary>
    public int QuantityChange { get; set; }
    public int PreviousQuantity { get; set; }
    public int NewQuantity { get; set; }

    public string Reason { get; set; } = string.Empty;

    /// <summary>Related document, e.g. an order number or receipt number.</summary>
    public string? Reference { get; set; }
    public int? StockReceiptId { get; set; }

    /// <summary>Null for automatic movements (checkout, payment expiry).</summary>
    public Guid? PerformedById { get; set; }
    public string PerformedByName { get; set; } = string.Empty;
    public DateTime CreatedUtc { get; set; }
}

/// <summary>Store-wide settings managed in the Owner Portal (single row, Id = 1).</summary>
public class StoreSettings
{
    public int Id { get; set; }

    /// <summary>A variant at or below this quantity (and above zero) counts as low stock, unless it has its own threshold.</summary>
    public int LowStockThreshold { get; set; } = 3;

    /// <summary>When the demo catalogue was seeded. Once set, deleted seed products are not re-created.</summary>
    public DateTime? CatalogSeededUtc { get; set; }

    public DateTime? ModifiedUtc { get; set; }
    public string? ModifiedByName { get; set; }
}

/// <summary>Who did what in the Owner Portal.</summary>
public class AdminAuditLog
{
    public long Id { get; set; }

    /// <summary>e.g. product.created, product.updated, order.status, inventory.adjusted.</summary>
    public string Action { get; set; } = string.Empty;
    public string EntityType { get; set; } = string.Empty;
    public string EntityId { get; set; } = string.Empty;
    public string Summary { get; set; } = string.Empty;
    public Guid? PerformedById { get; set; }
    public string PerformedByName { get; set; } = string.Empty;
    public DateTime CreatedUtc { get; set; }
}
